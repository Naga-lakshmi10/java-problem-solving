        System.out.println();
        System.out.println("1. ABOUT JAVA");
        System.out.println("--------------------------------------------------");
        System.out.println("Java is a high-level, general-purpose programming");
        System.out.println("language used to develop different types of");
        System.out.println("applications.");

        // 2. Java Platform
        System.out.println();
        System.out.println("2. JAVA PLATFORM");
        System.out.println("--------------------------------------------------");
        System.out.println("Java SE      : Standard Java platform");
        System.out.println("Jakarta EE   : Enterprise application platform");
        System.out.println("Java ME      : Platform for resource-constrained");
