public class OutputStatements {

    public static void main(String[] args) {

        // Demonstrating print() and println()
        System.out.print("Java ");
        System.out.print("Java");
        System.out.println();

        System.out.println("Programming");
        System.out.println("Language");

        // Formatted section
        System.out.println();
        System.out.println("------------------------------");
        System.out.println("OUTPUT STATEMENTS");
        System.out.println("------------------------------");
        System.out.println("print()   : Prints without a new line");
        System.out.println("println() : Prints with a new line");
        System.out.println("------------------------------");
    }
}