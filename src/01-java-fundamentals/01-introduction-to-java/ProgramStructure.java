public class ProgramStructure {

    public static void main(String[] args) {

        // Displaying the structure of a basic Java program
        System.out.println("==================================================");
        System.out.println("           JAVA PROGRAM STRUCTURE");
        System.out.println("==================================================");

        // Program information
        System.out.println("Program Name : ProgramStructure");
        System.out.println("Entry Point  : main()");
        System.out.println("Output       : Console");

        // Demonstrating statements inside main()
        System.out.println("Message 1    : Java program execution begins");
        System.out.println("               from the main() method.");

        System.out.println("Message 2    : Statements are placed inside");
        System.out.println("               the main() method.");

        System.out.println("Message 3    : System.out.println() displays");
        System.out.println("               output on the console.");

        System.out.println("==================================================");
    }
}