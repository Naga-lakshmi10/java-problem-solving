public class VariableStateTracking
{
    public static void main(String[] args)
    {
        int currentSemester=4;
        System.out.println("Current semester: " + currentSemester);
        currentSemester=5;
        System.out.println("Updated semester: " + currentSemester);
        currentSemester=6;
        System.out.println("Final semester: " + currentSemester);
    }


}