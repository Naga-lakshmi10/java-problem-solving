public class CharacterAndBoolean {
    public static void main(String[] args) {

        char firstLetterOfName = 'N';
        char grade = 'A';
        char digitCharacter = '7';
        char specialCharacter = '@';

        System.out.println("First Letter of Name: " + firstLetterOfName);
        System.out.println("Grade: " + grade);
        System.out.println("Digit Character: " + digitCharacter);
        System.out.println("Special Character: " + specialCharacter);

        boolean isCurrentlyEnrolled = true;
        boolean completedSemester = true;
        boolean isJavaProgrammingLanguage = true;
        boolean comparisonResult = 10 > 20;

        System.out.println("Currently Enrolled: " + isCurrentlyEnrolled);
        System.out.println("Completed Semester: " + completedSemester);
        System.out.println("Java is a Programming Language: " + isJavaProgrammingLanguage);
        System.out.println("10 > 20: " + comparisonResult);

        System.out.println("New Line:\nNext Line");
        System.out.println("Tab:\tTabbed Text");
        System.out.println("Single Quote: \'");
        System.out.println("Double Quote: \"");
        System.out.println("Backslash: \\");
    }
}