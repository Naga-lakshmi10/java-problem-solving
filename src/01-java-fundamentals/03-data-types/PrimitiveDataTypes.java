public class PrimitiveDataTypes
{
    public static void main(String[] args)
    {
        short age=20;
        System.out.println("Age: "+age);
        String studentId="24A31A05GX";
        System.out.println("Student Id: "+studentId);
        byte numberOfSemestersCompleted=4;
        System.out.println("Number of Semesters: "+numberOfSemestersCompleted);
        char grade='A';
        System.out.println("Grade: "+grade);
        float cgpa=9.06f;
        System.out.println("CGPA: "+cgpa);
        double attendancePercentage=90;
        System.out.println("Attendance Percentage: "+attendancePercentage);
        boolean isCurrentlyEnrolled=true;
        System.out.println("Currently Enrolled: "+isCurrentlyEnrolled);
        int numberOfStudentsInClass=75;
        System.out.println("Number of Students in Class: "+numberOfStudentsInClass);
        long totalFee=1000000L;
        System.out.println("Total Fee: "+totalFee);
    }
}